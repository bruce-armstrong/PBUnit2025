<#
.SYNOPSIS
    Builds a PowerBuilder 2025 test project, runs its PBUnit tests and reports the results.

.DESCRIPTION
    1. Reads the project (.pbproj) for its application, entry library and library list.
    2. Finds test classes: *tests classes in those libraries that inherit from testcase.
    3. Generates n_pbunit_registry.sru into the entry library (do not commit it).
    4. Builds the project with PBAutoBuild (PBC approach) and moves the PBDs next to the exe.
    5. Runs the exe and prints the text results.

    Exit codes: 0 = all tests passed, 1 = test failures, 2 = build, run or setup problem.

.EXAMPLE
    pwsh -File Invoke-PBUnit.ps1 -Project C:\src\MyApp\myapp_tests.pbproj
.EXAMPLE
    pwsh -File Invoke-PBUnit.ps1 -Project .\myapp_tests.pbproj -Filter "n_cst_string_tests.test_trim*"
#>
param(
    [Parameter(Mandatory = $true)]
    [string]$Project,
    # Output folder for the exe, PBDs and results; default build\<project name> beside the project.
    [string]$OutDir,
    # Comma-separated class or class.test names; a trailing * matches a prefix.
    [string]$Filter,
    [int]$TimeoutSeconds = 300,
    [string]$PBAutoBuild = "C:\Program Files (x86)\Appeon\PowerBuilder 25.0\pbautobuild250.exe"
)

$ErrorActionPreference = "Stop"

$projectPath = (Resolve-Path $Project).Path
$root        = Split-Path -Parent $projectPath
$projectName = [IO.Path]::GetFileNameWithoutExtension($projectPath)
[xml]$xml    = Get-Content $projectPath -Raw

$appName   = $xml.Project.Application.Name
$entryLib  = Join-Path $root $xml.Project.Libraries.AppEntry
$libraries = @($xml.Project.Libraries.Library | ForEach-Object { Join-Path $root $_.Path })

if (-not $OutDir) { $OutDir = Join-Path $root "build\$projectName" }
New-Item -ItemType Directory -Force $OutDir | Out-Null
$OutDir   = (Resolve-Path $OutDir).Path
$exe      = Join-Path $OutDir "$appName.exe"
$textOut  = Join-Path $OutDir "results.txt"
$junitOut = Join-Path $OutDir "results.xml"
$buildLog = Join-Path $OutDir "build.log"

# --- Discover test classes -------------------------------------------------
# Map every user object to its ancestor, then keep *tests classes whose
# ancestor chain reaches testcase.
$ancestors = @{}
foreach ($lib in $libraries) {
    if (-not (Test-Path $lib)) { continue }
    foreach ($file in Get-ChildItem $lib -Filter *.sru -File) {
        $match = Select-String -Path $file.FullName -Pattern '^global type (\w+) from (\w+)' | Select-Object -First 1
        if ($match) { $ancestors[$match.Matches[0].Groups[1].Value.ToLower()] = $match.Matches[0].Groups[2].Value.ToLower() }
    }
}

$testClasses = @()
foreach ($name in $ancestors.Keys | Sort-Object) {
    if (-not $name.EndsWith("tests")) { continue }
    $current = $name
    for ($depth = 0; $depth -lt 50 -and $ancestors.ContainsKey($current); $depth++) {
        $current = $ancestors[$current]
        if ($current -eq "testcase") { $testClasses += $name; break }
    }
}

if ($testClasses.Count -eq 0) {
    Write-Host "No test classes found (classes ending in 'tests' that inherit from testcase)."
    exit 2
}
Write-Host "Test classes: $($testClasses -join ', ')"

$registry = @"
//objectcomments Generated by Invoke-PBUnit.ps1 - do not edit or commit
forward
global type n_pbunit_registry from nonvisualobject
end type
end forward

global type n_pbunit_registry from nonvisualobject
end type
global n_pbunit_registry n_pbunit_registry

forward prototypes
public function string of_gettestclasses ()
end prototypes

public function string of_gettestclasses ();Return "$($testClasses -join ',')"
end function

on n_pbunit_registry.create
call super::create
TriggerEvent( this, "constructor" )
end on

on n_pbunit_registry.destroy
TriggerEvent( this, "destructor" )
call super::destroy
end on
"@
$registryFile = Join-Path $entryLib "n_pbunit_registry.sru"
$registryText = ($registry -replace "`r?`n", "`r`n") + "`r`n"
if (-not (Test-Path $registryFile) -or (Get-Content $registryFile -Raw) -ne $registryText) {
    [IO.File]::WriteAllText($registryFile, $registryText, (New-Object Text.UTF8Encoding($true)))
}

# --- Build ----------------------------------------------------------------
Remove-Item $textOut, $junitOut -ErrorAction SilentlyContinue
Push-Location $root
try {
    $build = Start-Process -FilePath $PBAutoBuild -NoNewWindow -Wait -PassThru -RedirectStandardOutput $buildLog `
        -ArgumentList '/pbc', '/d', "`"$projectPath`"", '/o', "`"$exe`""
} finally {
    Pop-Location
}

# PBC writes each PBD beside its library folder; move them next to the exe.
foreach ($lib in $libraries) {
    $pbd = [IO.Path]::ChangeExtension($lib, ".pbd")
    if (Test-Path $pbd) { Move-Item $pbd $OutDir -Force }
}

$logText = [Text.Encoding]::Unicode.GetString([IO.File]::ReadAllBytes($buildLog))
if ($build.ExitCode -ne 0 -or $logText -notmatch "Successfully generated") {
    $logText -split "`r?`n" | Where-Object { $_ -match "\[Error\]|error C|failed" } | Select-Object -First 40
    Write-Host "Build failed; see $buildLog"
    exit 2
}

# --- Run ------------------------------------------------------------------
$arguments = @("/out:`"$textOut`"", "/junit:`"$junitOut`"")
if ($Filter) { $arguments += "/filter:`"$Filter`"" }

try {
    $run = Start-Process -FilePath $exe -ArgumentList $arguments -WorkingDirectory $OutDir -PassThru
} catch {
    Write-Host "Could not start $exe : $($_.Exception.Message)"
    exit 2
}
if (-not $run.WaitForExit($TimeoutSeconds * 1000)) {
    Stop-Process -Id $run.Id -Force
    Write-Host "Test run timed out after $TimeoutSeconds seconds (a dialog may have opened)."
    exit 2
}

if (Test-Path $textOut) { Get-Content $textOut } else { Write-Host "No results file was written." }
Write-Host "JUnit XML: $junitOut"

$code = $run.ExitCode
if ($code -notin 0, 1, 2) { $code = 2 }
exit $code
