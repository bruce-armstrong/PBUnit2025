<#
.SYNOPSIS
    Regenerates each eval case's scaffold.sh from its fixture folder and the framework files.

.DESCRIPTION
    For every case folder under plugins/pbunit/evals that has a fixture/ folder, writes scaffold.sh, a Bash
    script that recreates in the eval run's empty workspace:
      - every file under fixture/, at the same relative path, and
      - a copy of the framework (pbunit*.pbl, scripts, README.md, LICENSE, as tracked by git) in tests/framework.
    PowerBuilder source files (.sr?, .pbproj, .pblmeta) are written as UTF-8 with a byte order mark and CRLF
    line endings, as the PowerBuilder IDE saves them; other files are written as they are in fixture/.

    Run it after changing a fixture or the framework, and commit the regenerated scaffold.sh files.
#>
$ErrorActionPreference = "Stop"

$evals = $PSScriptRoot
$repo  = (Resolve-Path (Join-Path $evals "..\..\..")).Path
$delimiter = "PBUNIT_EOF"

function Read-Normalized([string]$path) {
    $text = [IO.File]::ReadAllText($path)
    if ($text.Length -gt 0 -and $text[0] -eq [char]0xFEFF) { $text = $text.Substring(1) }
    return ($text -replace "`r`n", "`n").TrimEnd("`n")
}

$framework = [ordered]@{}
foreach ($rel in (git -C $repo ls-files pbunit.pbl pbunitfunc.pbl pbunitrunner.pbl scripts README.md LICENSE)) {
    $framework["tests/framework/$rel"] = Read-Normalized (Join-Path $repo $rel)
}

foreach ($case in Get-ChildItem $evals -Directory) {
    $fixture = Join-Path $case.FullName "fixture"
    if (-not (Test-Path $fixture)) { continue }

    $files = [ordered]@{}
    foreach ($f in Get-ChildItem $fixture -Recurse -File | Sort-Object FullName) {
        $rel = $f.FullName.Substring($fixture.Length + 1) -replace '\\', '/'
        $files[$rel] = Read-Normalized $f.FullName
    }
    foreach ($k in $framework.Keys) { $files[$k] = $framework[$k] }

    $sb = New-Object Text.StringBuilder
    [void]$sb.Append("#!/usr/bin/env bash`n")
    [void]$sb.Append("# Generated by plugins/pbunit/evals/Update-Scaffolds.ps1 from fixture/ and the framework files. Do not edit.`n")
    [void]$sb.Append("set -euo pipefail`n`n")
    foreach ($k in $files.Keys) {
        if ($files[$k] -match "(?m)^$delimiter$") { throw "$($case.Name): $k contains the line $delimiter" }
        $dir = Split-Path $k -Parent
        if ($dir) { [void]$sb.Append("mkdir -p '$($dir -replace '\\', '/')'`n") }
        [void]$sb.Append("cat > '$k' <<'$delimiter'`n$($files[$k])`n$delimiter`n`n")
    }
    [void]$sb.Append(@'
# PowerBuilder source files: UTF-8 with a byte order mark and CRLF line endings, as the IDE saves them.
find . -type f \( -name '*.sr?' -o -name '*.pbproj' -o -name '*.pblmeta' \) -print0 |
while IFS= read -r -d '' f; do
  { printf '\xEF\xBB\xBF'; sed 's/$/\r/' "$f"; } > "$f.tmp" && mv "$f.tmp" "$f"
done
'@)
    $out = Join-Path $case.FullName "scaffold.sh"
    [IO.File]::WriteAllText($out, ($sb.ToString() -replace "`r`n", "`n"), (New-Object Text.UTF8Encoding($false)))
    Write-Host ("{0}: {1} files ({2} from fixture)" -f $case.Name, $files.Count, ($files.Count - $framework.Count))
}
